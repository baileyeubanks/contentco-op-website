import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/**
 * The homepage hero video file name (for example "cco-hero-seamless-1080.mp4"),
 * read from app/hero-video-config.ts so the audit follows the configured hero
 * instead of a hard-coded, retired file name.
 */
export function readHeroVideoMarker(root = appRoot) {
  const source = fs.readFileSync(path.resolve(root, "app/hero-video-config.ts"), "utf8");
  const match = source.match(/HERO_VIDEO_FILENAME\s*=\s*"([^"]+)"/);
  if (!match?.[1]) {
    throw new Error("HERO_VIDEO_FILENAME missing from app/hero-video-config.ts");
  }
  return path.posix.basename(match[1]);
}

